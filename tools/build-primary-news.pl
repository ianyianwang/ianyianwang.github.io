#!/usr/bin/perl
# Builds primary-news.html: a stand-alone copy of primary-newsroom.html for parents.
# Same stories, but no site menu, no links to the rest of the site, no student footer.
# Run from the repo root after any change to primary-newsroom.html:
#   perl tools/build-primary-news.pl
use strict; use warnings;
local $/;
open my $in, '<', 'primary-newsroom.html' or die "primary-newsroom.html: $!";
my $src = <$in>; close $in;

my ($stories) = $src =~ m{(<section class="posts">.*?</section>)}s
  or die "Could not find the posts section";

my $page = <<"HTML";
<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="robots" content="noindex">
  <title>Primary Student Newsroom</title>
  <meta name="description" content="News stories written by our Primary student reporters.">
  <link rel="preconnect" href="https://fonts.googleapis.com">
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
  <link href="https://fonts.googleapis.com/css2?family=Fraunces:opsz,wght@9..144,600&family=Inter:wght@400;500;600&display=swap" rel="stylesheet">
  <link rel="stylesheet" href="style.css">
</head>
<body>
<!-- GENERATED by tools/build-primary-news.pl from primary-newsroom.html. Do not edit by hand. -->

<header class="top">
  <div class="wrap">
    <span class="brand">Primary Student <span>Newsroom</span></span>
  </div>
</header>

<main class="wrap">
  <section class="intro">
    <p class="eyebrow">Written by students</p>
    <h1>Primary Student Newsroom</h1>
    <p>News stories from our Primary student reporters, in their own words. No AI, ever.</p>
  </section>

  $stories
</main>

<footer>
  <div class="wrap">
    <p class="small">Written and reported by our Primary student reporters.</p>
  </div>
</footer>

</body>
</html>
HTML

open my $out, '>', 'primary-news.html' or die "primary-news.html: $!";
print $out $page; close $out;
print "Built primary-news.html\n";
